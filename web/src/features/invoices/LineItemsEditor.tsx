import { useFieldArray, type Control, type FieldErrors, type UseFormRegister } from 'react-hook-form'
import { Button } from '@/components/ui/Button'
import { formatAmount, lineTotal, parseMoney, parseQuantityMilli, VAT_RATES } from './money'
import { emptyLine, type InvoiceFormValues, type LineItemFormValues } from './schema'

type LineItemsEditorProps = {
  control: Control<InvoiceFormValues>
  register: UseFormRegister<InvoiceFormValues>
  errors: FieldErrors<InvoiceFormValues>
  /** Current values from useWatch, used for the per-line amount column. */
  items: LineItemFormValues[]
}

const inputClass = (invalid: boolean) =>
  `block w-full rounded-md border bg-white px-2.5 py-1.5 text-sm shadow-sm outline-none focus:ring-2 ${
    invalid ? 'border-rose-300 focus:ring-rose-100' : 'border-slate-300 focus:border-brand-500 focus:ring-brand-100'
  }`

/**
 * useFieldArray = a dynamic list of sub-forms. Each row needs a stable `key`
 * (field.id, generated by RHF), never the array index: with index keys, deleting
 * row 2 would make React reuse row 2's DOM inputs for what used to be row 3.
 */
export function LineItemsEditor({ control, register, errors, items }: LineItemsEditorProps) {
  const { fields, append, remove, move } = useFieldArray({ control, name: 'items' })
  const arrayError = errors.items?.root?.message ?? errors.items?.message

  return (
    <div>
      <div className="hidden grid-cols-[minmax(0,1fr)_6rem_8rem_8.5rem_7rem_4.5rem] gap-3 px-1 pb-2 text-xs font-medium uppercase tracking-wide text-slate-500 md:grid">
        <span>Description</span>
        <span className="text-right">Qty</span>
        <span className="text-right">Unit price</span>
        <span>VAT</span>
        <span className="text-right">Amount</span>
        <span className="sr-only">Actions</span>
      </div>

      <ol className="space-y-3">
        {fields.map((field, index) => {
          const rowErrors = errors.items?.[index]
          const current = items[index]
          const amount = current
            ? lineTotal(parseQuantityMilli(current.quantity) ?? 0, parseMoney(current.unit_price) ?? 0)
            : 0
          const messages = [
            rowErrors?.description?.message,
            rowErrors?.quantity?.message && `Qty: ${rowErrors.quantity.message}`,
            rowErrors?.unit_price?.message && `Price: ${rowErrors.unit_price.message}`,
            rowErrors?.vat_rate?.message,
          ].filter(Boolean)

          return (
            <li key={field.id} className="rounded-lg border border-slate-200 p-3 md:border-0 md:p-0">
              <div className="grid grid-cols-2 gap-3 md:grid-cols-[minmax(0,1fr)_6rem_8rem_8.5rem_7rem_4.5rem] md:items-start">
                <label className="col-span-2 md:col-span-1">
                  <span className="sr-only">Description, line {index + 1}</span>
                  <input
                    placeholder="What did you provide?"
                    aria-invalid={Boolean(rowErrors?.description) || undefined}
                    className={inputClass(Boolean(rowErrors?.description))}
                    {...register(`items.${index}.description`)}
                  />
                </label>
                <label>
                  <span className="text-xs text-slate-500 md:sr-only">Quantity</span>
                  <input
                    inputMode="decimal"
                    aria-invalid={Boolean(rowErrors?.quantity) || undefined}
                    className={`${inputClass(Boolean(rowErrors?.quantity))} text-right tabular-nums`}
                    {...register(`items.${index}.quantity`)}
                  />
                </label>
                <label>
                  <span className="text-xs text-slate-500 md:sr-only">Unit price (AED)</span>
                  <input
                    inputMode="decimal"
                    placeholder="0.00"
                    aria-invalid={Boolean(rowErrors?.unit_price) || undefined}
                    className={`${inputClass(Boolean(rowErrors?.unit_price))} text-right tabular-nums`}
                    {...register(`items.${index}.unit_price`)}
                  />
                </label>
                <label>
                  <span className="text-xs text-slate-500 md:sr-only">VAT treatment</span>
                  <select className={inputClass(Boolean(rowErrors?.vat_rate))} {...register(`items.${index}.vat_rate`)}>
                    {VAT_RATES.map((rate) => (
                      <option key={rate.value} value={rate.value}>
                        {rate.label}
                      </option>
                    ))}
                  </select>
                </label>
                <div className="self-center text-right text-sm font-medium tabular-nums text-slate-900">
                  <span className="text-xs font-normal text-slate-500 md:hidden">Amount </span>
                  {formatAmount(amount)}
                </div>
                <div className="flex items-center justify-end gap-0.5 self-center">
                  <IconButton
                    label={`Move line ${index + 1} up`}
                    disabled={index === 0}
                    onClick={() => move(index, index - 1)}
                    path="M10 15V5m0 0-4 4m4-4 4 4"
                  />
                  <IconButton
                    label={`Remove line ${index + 1}`}
                    disabled={fields.length === 1}
                    onClick={() => remove(index)}
                    path="M6 6l8 8M14 6l-8 8"
                    danger
                  />
                </div>
              </div>
              {messages.length > 0 && <p className="mt-1.5 text-sm text-rose-600">{messages.join(' · ')}</p>}
            </li>
          )
        })}
      </ol>

      {arrayError && <p className="mt-2 text-sm text-rose-600">{arrayError}</p>}

      <Button variant="secondary" size="sm" className="mt-4" onClick={() => append({ ...emptyLine })}>
        + Add line
      </Button>
    </div>
  )
}

function IconButton({
  label,
  path,
  onClick,
  disabled,
  danger = false,
}: {
  label: string
  path: string
  onClick: () => void
  disabled?: boolean
  danger?: boolean
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      aria-label={label}
      title={label}
      className={`rounded-md p-1.5 text-slate-400 transition disabled:opacity-30 ${
        danger ? 'hover:bg-rose-50 hover:text-rose-600' : 'hover:bg-slate-100 hover:text-slate-700'
      }`}
    >
      <svg viewBox="0 0 20 20" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" className="size-4" aria-hidden="true">
        <path d={path} />
      </svg>
    </button>
  )
}
